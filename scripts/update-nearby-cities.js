#!/usr/bin/env node
// Adds or refreshes a "Nearby Cities" section on every city page: the 3 closest
// city guides plus a link to the country guide. Re-run after adding a city page so
// its neighbours pick it up too:
//   node scripts/update-nearby-cities.js            # write
//   node scripts/update-nearby-cities.js --dry-run  # print pairings only
//
// Coordinates come from each country page's `{ name, slug, lat, lon }` city list;
// the GF score comes from each city page's meta description ("N/10").

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const DRY = process.argv.includes('--dry-run');
const MAX_CARDS = 3;
const MAX_OTHER_COUNTRY_KM = 1000; // same-country cities count at any distance

const COUNTRY_NAMES = { usa: 'United States' };
function countryName(slug) {
  return COUNTRY_NAMES[slug] || slug.split('-').map((w) => w[0].toUpperCase() + w.slice(1)).join(' ');
}

function km(a, b) {
  const r = (d) => (d * Math.PI) / 180;
  const h = Math.sin(r(b.lat - a.lat) / 2) ** 2 +
    Math.cos(r(a.lat)) * Math.cos(r(b.lat)) * Math.sin(r(b.lon - a.lon) / 2) ** 2;
  return 2 * 6371 * Math.asin(Math.sqrt(h));
}

function escapeHtml(s) {
  return s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

// ── Collect cities ──────────────────────────────────────────
const countriesDir = path.join(ROOT, 'countries');
const cities = [];
for (const file of fs.readdirSync(countriesDir).filter((f) => f.endsWith('.html'))) {
  const country = file.replace(/\.html$/, '');
  const html = fs.readFileSync(path.join(countriesDir, file), 'utf8');
  const re = /\{\s*name:\s*'([^']+)',\s*slug:\s*'([^']+)',\s*lat:\s*([-\d.]+),\s*lon:\s*([-\d.]+)/g;
  let m;
  while ((m = re.exec(html))) {
    const page = path.join(countriesDir, country, `${m[2]}.html`);
    if (!fs.existsSync(page)) continue;
    const desc = (fs.readFileSync(page, 'utf8').match(/<meta name="description" content="([^"]*)"/) || [])[1] || '';
    const score = (desc.match(/(\d+)\/10/) || [])[1];
    cities.push({ name: m[1], slug: m[2], country, lat: +m[3], lon: +m[4], score, page });
  }
}

// ── Build sections ──────────────────────────────────────────
const START = '<!-- NEARBY CITIES (generated by scripts/update-nearby-cities.js; edit the script, not this block) -->';
const END = '<!-- /NEARBY CITIES -->';
const CSS_MARK = '/* ─── Nearby cities (scripts/update-nearby-cities.js) ─── */';
const CSS = `
    ${CSS_MARK}
    .nearby { padding: 3rem 2.5rem 0; }
    .nearby-label { font-family: 'Cormorant Garamond', serif; font-weight: 300; font-size: 0.72rem; letter-spacing: 0.2em; text-transform: uppercase; color: var(--ink-light); margin-bottom: 1rem; }
    .nearby-grid { display: flex; flex-wrap: wrap; gap: 1px; background: rgba(42, 32, 24, 0.08); border: 1px solid rgba(42, 32, 24, 0.08); }
    .nearby-card { flex: 1 1 200px; background: var(--cream); padding: 1.3rem 1.4rem; text-decoration: none; display: flex; flex-direction: column; gap: 0.3rem; transition: opacity 0.2s ease; }
    .nearby-card:hover, .nearby-card:focus-visible { background: var(--slate-bg); }
    .nearby-card:focus-visible { outline: 1.5px solid var(--slate); outline-offset: -3px; }
    .nearby-card:active { opacity: 0.7; }
    .nearby-eyebrow { font-family: 'Jost', sans-serif; font-size: 0.56rem; font-weight: 400; letter-spacing: 0.18em; text-transform: uppercase; color: var(--ink-light); }
    .nearby-name { font-family: 'Cormorant Garamond', serif; font-size: 1.15rem; color: var(--ink); }
    .nearby-card:hover .nearby-name, .nearby-card:focus-visible .nearby-name { color: var(--slate); }
    @media (max-width: 600px) { .nearby { padding-left: 1.2rem; padding-right: 1.2rem; } }
`;

function section(city) {
  const picks = cities
    .filter((o) => o !== city)
    .map((o) => ({ o, d: km(city, o) }))
    .filter(({ o, d }) => o.country === city.country || d <= MAX_OTHER_COUNTRY_KM)
    .sort((a, b) => a.d - b.d)
    .slice(0, MAX_CARDS);

  const card = (href, eyebrow, name) =>
    `      <a href="${href}" class="nearby-card">\n` +
    `        <span class="nearby-eyebrow">${escapeHtml(eyebrow)}</span>\n` +
    `        <span class="nearby-name">${escapeHtml(name)}</span>\n` +
    `      </a>`;

  const cards = picks.map(({ o, d }) => {
    const href = o.country === city.country ? o.slug : `../${o.country}/${o.slug}`;
    const dist = d < 10 ? 'under 10 km' : `${Math.round(d / 5) * 5} km away`;
    const eyebrow = [countryName(o.country), dist, o.score ? `GF ${o.score}/10` : null].filter(Boolean).join(' · ');
    return { html: card(href, eyebrow, `${o.name} →`), picked: `${o.name} (${Math.round(d)} km)` };
  });
  cards.push({ html: card(`../${city.country}`, 'Country Guide', `All of ${countryName(city.country)} →`) });

  const html = `  ${START}\n  <section class="nearby" aria-label="Nearby city guides">\n` +
    `    <div class="nearby-label">Nearby Cities</div>\n    <div class="nearby-grid">\n` +
    cards.map((c) => c.html).join('\n') + '\n    </div>\n  </section>\n' +
    `  <script>\n    document.querySelectorAll('.nearby-card').forEach(function (a) {\n` +
    `      a.addEventListener('click', function () {\n` +
    `        if (typeof gtag === 'function') gtag('event', 'nearby_city_click', { event_category: 'navigation', event_label: this.querySelector('.nearby-name').textContent.replace(' →', ''), link_url: this.href });\n` +
    `      });\n    });\n  </script>\n  ${END}\n\n`;
  return { html, picked: cards.filter((c) => c.picked).map((c) => c.picked) };
}

let written = 0;
for (const city of cities) {
  const { html: block, picked } = section(city);
  if (DRY) { console.log(`${city.name.padEnd(22)} -> ${picked.join(', ')}`); continue; }

  let s = fs.readFileSync(city.page, 'utf8');
  const before = s;
  if (!s.includes(CSS_MARK)) {
    const i = s.indexOf('</style>');
    s = s.slice(0, i) + CSS.replace(/^\n/, '') + '  ' + s.slice(i);
  }
  const startIdx = s.indexOf(START);
  if (startIdx !== -1) {
    // Replace the whole previously generated block, from the start of its line through the blank line after it.
    const lineStart = s.lastIndexOf('\n', startIdx) + 1;
    const endIdx = s.indexOf(END, startIdx) + END.length;
    s = s.slice(0, lineStart) + block + s.slice(endIdx).replace(/^\n+/, '');
  } else {
    const anchor = s.search(/[ \t]*<!-- TIP CTA -->|[ \t]*<(?:div|section) class="tip-cta">/);
    if (anchor === -1) { console.warn(`No tip-cta anchor, skipped: ${city.page}`); continue; }
    s = s.slice(0, anchor) + block + s.slice(anchor);
  }
  if (s !== before) { fs.writeFileSync(city.page, s); written++; }
}
if (!DRY) console.log(`Nearby Cities updated on ${written} of ${cities.length} city pages`);
